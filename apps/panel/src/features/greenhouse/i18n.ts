const TEXT = { en, fa, ar } as const;

/** A name the server gives in each language, or the grower's own one. */
export function nameIn(
  language: "en" | "fa" | "ar",
  names: LocalizedNames | undefined | null,
  own?: string | null,
): string {
  if (own && own.trim()) return own;
  return names?.[language] || names?.en || "";
}

export function useGreenhouseText() {
  const { language, formatNumber, isRTL } = useLanguage();
  const g = useCallback(
    (key: GreenhouseTextKey, vars?: Record<string, string | number>) => {
      let text: string = TEXT[language]?.[key] ?? en[key] ?? key;
      if (vars) {
        for (const [name, value] of Object.entries(vars)) {
          text = text.split(`{${name}}`).join(typeof value === "number" ? formatNumber(value) : value);
        }
      }
      return text;
    },
    [language, formatNumber],
  );
  const named = useCallback(
    (names: LocalizedNames | undefined | null, own?: string | null) => nameIn(language, names, own),
    [language],
  );
  return { g, named, language, isRTL, formatNumber };
}
